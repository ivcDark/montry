## Как не пропустить настоящее падение

Подтверждение не должно быть слишком длинным. Если интервал проверки пять минут, а инцидент открывается только после десяти неудач, команда узнает о проблеме слишком поздно. Баланс обычно такой: подтвердить сбой быстро, но не реагировать на единичный сбой сети.

Параллельно имеет смысл мониторить не только «сайт жив/не жив», но и связанные риски: SSL, срок домена, DNS. Иногда «падение» начинается с истекшего сертификата или сломанного DNS, а HTTP-проверка лишь фиксирует следствие.

