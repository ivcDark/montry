- закрывать инцидент после одного или нескольких успешных восстановлений;
- считать длительность простоя автоматически.

Так история инцидентов отражает реальные проблемы, а не сетевой шум. Это важно и для владельца одного сайта, и для мониторинга для веб-студий с большой клиентской базой.

