## Какие статусы встречаются чаще всего

В проверке доступности сайта полезно понимать базовую карту кодов:

- 200 — страница открылась нормально;
- 301/302 — редирект, иногда это ожидаемое поведение;
- 401/403 — доступ ограничен, для закрытых разделов может быть нормой;
- 404 — страница не найдена, часто сигнал ошибки после деплоя;
- 500–504 — ошибка сервера или шлюза, почти всегда повод для инцидента.

Смысл мониторинга не в том, чтобы любой код кроме 200 считать аварией, а в том, чтобы сравнивать ответ с ожиданием для конкретного URL.

## Что настраивать у HTTP-монитора

Для гибкой проверки доступности обычно нужны:

- метод запроса;
- URL;
- follow redirects;
- verify SSL;
- таймаут;
- список допустимых статус-кодов;
- при необходимости ограничение по времени ответа.

Такой набор позволяет мониторить и публичные страницы, и API, не переписывая ядро сервиса под каждый кейс.

## Типичные ошибки настройки

Частая ошибка — мониторить только главную. Рекламный лендинг, форма заявки или checkout могут лежать отдельно, пока главная отдаёт 200. Другая ошибка — игнорировать редиректы: цепочка редиректов может внезапно сломаться после смены CMS или DNS.

Также стоит отдельно продумать таймауты. Слишком мягкий порог скрывает деградацию. Слишком жёсткий — создаёт ложные падения на кратковременных задержках сети.

## Как связать статусы с инцидентами

HTTP-код сам по себе ещё не инцидент. Один неудачный чек может быть сетевой случайностью. Надёжнее открывать инцидент после нескольких подтверждённых провалов подряд, а закрывать — после стабильного восстановления.

Так уведомления о падении сайта остаются полезными: команда видит реальные простои и не тонет в шуме.

