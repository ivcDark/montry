Календарь зависит от человека. Сотрудник уволился, письмо ушло в спам, задача потерялась в трекере — и дата прошла незаметно. Автопродление тоже не гарантия: сертификат мог обновиться на одном хосте, а на CDN или поддомене остаться старым.

Мониторинг SSL смотрит на то, что видит пользователь: дату окончания, базовую валидность и приближение критической даты. Это проверка факта, а не надежда, что процесс продления сработал.

